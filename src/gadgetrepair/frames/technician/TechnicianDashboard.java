    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
 String search = txtSearchRepair.getText().trim();

    if (search.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Please enter a customer name, gadget, or problem."
        );

        loadRepairs();
        return;
    }

    DefaultTableModel model =
        (DefaultTableModel) tblRepairs.getModel();

    model.setRowCount(0);

    String sql =
        "SELECT " +
        "r.repair_id, " +
        "CONCAT(c.first_name, ' ', c.last_name) AS customer_name, " +
        "CONCAT(g.brand_model, ' - ', g.gadget_type) AS gadget_name, " +
        "r.repair_description AS problem, " +
        "a.username AS technician, " +
        "r.date_brought, " +
        "r.repair_status " +
        "FROM repairs r " +
        "JOIN gadgets g ON r.gadget_id = g.gadget_id " +
        "JOIN customers c ON g.customer_id = c.customer_id " +
        "LEFT JOIN technicians t ON r.technician_id = t.technician_id " +
        "LEFT JOIN accounts a ON t.account_id = a.account_id " +
        "WHERE r.technician_id = ? " +
        "AND r.is_archived = 0 " +
        "AND (" +
        "CONCAT(c.first_name, ' ', c.last_name) LIKE ? " +
        "OR g.brand_model LIKE ? " +
        "OR g.gadget_type LIKE ? " +
        "OR r.repair_description LIKE ?" +
        ") " +
        "ORDER BY r.repair_id DESC";

    try (
        Connection conn = DatabaseConnection.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql)
    ) {

        String keyword = "%" + search + "%";

        // Technician ID
        pst.setInt(1, technicianId);

        // Search keyword
        pst.setString(2, keyword);
        pst.setString(3, keyword);
        pst.setString(4, keyword);
        pst.setString(5, keyword);

        try (ResultSet rs = pst.executeQuery()) {

            boolean found = false;

            while (rs.next()) {

                found = true;

                model.addRow(new Object[]{
                    rs.getInt("repair_id"),
                    rs.getString("customer_name"),
                    rs.getString("gadget_name"),
                    rs.getString("problem"),
                    rs.getString("technician"),
                    rs.getDate("date_brought"),
                    rs.getString("repair_status")
                });
            }

            if (!found) {

                JOptionPane.showMessageDialog(
                    this,
                    "No matching repair found."
                );

                loadRepairs();
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error searching repairs:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }// TODO add your handling code here:
    }//GEN-LAST:event_btnSearchActionPerformed

