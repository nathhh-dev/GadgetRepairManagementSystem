   private void loadRepairs() {

    String sql =
        "SELECT " +
        "r.repair_id, " +
        "CONCAT(c.first_name, ' ', c.last_name) AS customer, " +
        "CONCAT(g.brand_model, ' - ', g.gadget_type) AS gadget, " +
        "r.repair_description AS problem, " +
        "a.username AS technician, " +
        "r.date_brought, " +
        "r.repair_status " +
        "FROM repairs r " +
        "JOIN gadgets g ON r.gadget_id = g.gadget_id " +
        "JOIN customers c ON g.customer_id = c.customer_id " +
        "LEFT JOIN technicians t ON r.technician_id = t.technician_id " +
        "LEFT JOIN accounts a ON t.account_id = a.account_id " +
        "WHERE r.technician_id = ? " +
        "AND r.is_archived = 0 " +
        "ORDER BY r.repair_id DESC";

    try (
        Connection conn = DatabaseConnection.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql)
    ) {

        pst.setInt(1, technicianId);

        try (ResultSet rs = pst.executeQuery()) {

            DefaultTableModel model =
                (DefaultTableModel) tblRepairs.getModel();

            model.setRowCount(0);

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getInt("repair_id"),
                    rs.getString("customer"),
                    rs.getString("gadget"),
                    rs.getString("problem"),
                    rs.getString("technician"),
                    rs.getDate("date_brought"),
                    rs.getString("repair_status")
                });
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error loading repairs:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}

