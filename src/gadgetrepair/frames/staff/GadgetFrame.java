    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed

        int row = tblGadgets.getSelectedRow();

        if (row < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a gadget to edit."
            );

            return;
        }

        int gadgetId =
                Integer.parseInt(
                        tblGadgets.getValueAt(row, 0).toString()
                );

        int customerId =
                Integer.parseInt(
                        tblGadgets.getValueAt(row, 1).toString()
                );

        String gadgetType =
                tblGadgets.getValueAt(row, 2).toString();

        String brandModel =
                tblGadgets.getValueAt(row, 3).toString();

        String problem =
                tblGadgets.getValueAt(row, 4).toString();

        // Put gadget information into form
        txtGadgetId.setText(
                String.valueOf(gadgetId)
        );

        txtGadgetType.setText(gadgetType);
        txtBrandModel.setText(brandModel);
        txtProblem.setText(problem);

        // Load customer information
        loadCustomerInformation(customerId);
    }

