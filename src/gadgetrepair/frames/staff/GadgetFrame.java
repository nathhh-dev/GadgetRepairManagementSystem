    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
  
        String customerIdText =
                txtSelectedCustomerId.getText().trim();

        String gadgetType =
                txtGadgetType.getText().trim();

        String brandModel =
                txtBrandModel.getText().trim();

        String problem =
                txtProblem.getText().trim();

        // Customer must be selected first
        if (customerIdText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please search and select a customer first."
            );

            return;
        }

        // Gadget information must be complete
        if (gadgetType.isEmpty()
                || brandModel.isEmpty()
                || problem.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please complete all gadget fields."
            );

            return;
        }

        try {

            int customerId =
                    Integer.parseInt(customerIdText);

            String sql =
                    "INSERT INTO gadgets " +
                    "(customer_id, gadget_type, brand_model, problem, is_active) " +
                    "VALUES (?, ?, ?, ?, 1)";

            try (
                    Connection conn =
                            DatabaseConnection.getConnection();

                    PreparedStatement pst =
                            conn.prepareStatement(sql)
            ) {

                pst.setInt(1, customerId);
                pst.setString(2, gadgetType);
                pst.setString(3, brandModel);
                pst.setString(4, problem);

                pst.executeUpdate();
            }

            JOptionPane.showMessageDialog(
                    this,
                    "Gadget added successfully!"
            );

            refreshGadgetTable();

            clearGadgetForm();

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid Customer ID."
            );

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error adding gadget:\n" + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }   // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

