                txtGadgetType.getText().trim();

        String brandModel =
                txtBrandModel.getText().trim();

        String problem =
                txtProblem.getText().trim();

        // Gadget ID is required when editing
        if (gadgetIdText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please click EDIT on a gadget first."
            );

            return;
        }

        // Customer is required
        if (customerIdText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a customer first."
            );

            return;
        }

        // Gadget information is required
        if (gadgetType.isEmpty()
                || brandModel.isEmpty()
                || problem.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please complete all gadget fields."
            );

            return;
        }

        try {

            int gadgetId =
                    Integer.parseInt(gadgetIdText);

            int customerId =
                    Integer.parseInt(customerIdText);

            String sql =
                    "UPDATE gadgets SET " +
                    "customer_id = ?, " +
                    "gadget_type = ?, " +
                    "brand_model = ?, " +
                    "problem = ? " +
                    "WHERE gadget_id = ? " +
                    "AND is_active = 1";

            try (
                    Connection conn =
                            DatabaseConnection.getConnection();

                    PreparedStatement pst =
                            conn.prepareStatement(sql)
            ) {

                pst.setInt(1, customerId);
                pst.setString(2, gadgetType);
                pst.setString(3, brandModel);
                pst.setString(4, problem);
                pst.setInt(5, gadgetId);

                int rowsUpdated =
                        pst.executeUpdate();

                if (rowsUpdated == 0) {

                    JOptionPane.showMessageDialog(
                            this,
                            "Gadget could not be updated."
                    );

                    return;
                }
            }

            JOptionPane.showMessageDialog(
                    this,
                    "Gadget updated successfully!"
            );

            refreshGadgetTable();

            clearGadgetForm();

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid ID."
            );

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error updating gadget:\n"
                    + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    
