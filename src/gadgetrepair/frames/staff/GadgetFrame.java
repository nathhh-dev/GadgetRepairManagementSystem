    // LOAD ALL ACTIVE GADGETS
    // =========================================================

    private void refreshGadgetTable() {

        DefaultTableModel model =
                (DefaultTableModel) tblGadgets.getModel();

        model.setRowCount(0);

        String sql =
                "SELECT gadget_id, customer_id, " +
                "gadget_type, brand_model, problem " +
                "FROM gadgets " +
                "WHERE is_active = 1 " +
                "ORDER BY gadget_id";

        try (
                Connection conn = DatabaseConnection.getConnection();
                PreparedStatement pst = conn.prepareStatement(sql);
                ResultSet rs = pst.executeQuery()
        ) {

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getInt("gadget_id"),
                    rs.getInt("customer_id"),
                    rs.getString("gadget_type"),
                    rs.getString("brand_model"),
                    rs.getString("problem")
                });
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error loading gadgets:\n" + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

