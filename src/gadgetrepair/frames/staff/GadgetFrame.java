    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
  String search =
                txtGadgetSearch.getText().trim();

        DefaultTableModel model =
                (DefaultTableModel) tblGadgets.getModel();

        model.setRowCount(0);

        if (search.isEmpty()) {

            refreshGadgetTable();
            return;
        }

        String sql =
                "SELECT gadget_id, customer_id, " +
                "gadget_type, brand_model, problem " +
                "FROM gadgets " +
                "WHERE is_active = 1 " +
                "AND (" +
                "CAST(gadget_id AS CHAR) LIKE ? " +
                "OR CAST(customer_id AS CHAR) LIKE ? " +
                "OR gadget_type LIKE ? " +
                "OR brand_model LIKE ? " +
                "OR problem LIKE ?" +
                ") " +
                "ORDER BY gadget_id";

        try (
                Connection conn =
                        DatabaseConnection.getConnection();

                PreparedStatement pst =
                        conn.prepareStatement(sql)
        ) {

            String keyword =
                    "%" + search + "%";

            pst.setString(1, keyword);
            pst.setString(2, keyword);
            pst.setString(3, keyword);
            pst.setString(4, keyword);
            pst.setString(5, keyword);

            try (ResultSet rs = pst.executeQuery()) {

                boolean found = false;

                while (rs.next()) {

                    model.addRow(new Object[]{
                        rs.getInt("gadget_id"),
                        rs.getInt("customer_id"),
                        rs.getString("gadget_type"),
                        rs.getString("brand_model"),
                        rs.getString("problem")
                    });

                    found = true;
                }

                if (!found) {

                    JOptionPane.showMessageDialog(
                            this,
                            "Gadget not found."
                    );

                    refreshGadgetTable();
                }
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error searching gadgets:\n"
                    + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
          // TODO add your handling code here:
    }//GEN-LAST:event_btnSearchActionPerformed

