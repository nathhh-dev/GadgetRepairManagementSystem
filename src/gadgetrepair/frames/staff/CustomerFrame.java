private void refreshCustomerTable() {

   DefaultTableModel model =
            (DefaultTableModel) tblCustomers.getModel();

    model.setRowCount(0);

    String sql = "SELECT customer_id, first_name, last_name, contact_number " +
    "FROM customers " + "WHERE is_active = 1 " + "ORDER BY customer_id";

    try (
        Connection conn = DatabaseConnection.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery()
    ) {

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("customer_id"),
                rs.getString("first_name"),
                rs.getString("last_name"),
                rs.getString("contact_number")
            });
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error loading customers:\n" + e.getMessage()
        );
    }
}
    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
  String firstName = txtFirstName.getText().trim();
    String lastName = txtLastName.getText().trim();
    String contact = txtContact.getText().trim();

    // Check if fields are empty
    if (firstName.isEmpty() ||
        lastName.isEmpty() ||
        contact.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Please complete all fields."
        );

        return;
    }

    // Validate first name
    // Allows letters, spaces, hyphens, and apostrophes
    if (!firstName.matches("[a-zA-Z][a-zA-Z '-]*")) {

        JOptionPane.showMessageDialog(
            this,
            "First name must contain letters only."
        );

        return;
    }

    // Validate last name
    // Allows letters, spaces, hyphens, and apostrophes
    if (!lastName.matches("[a-zA-Z][a-zA-Z '-]*")) {

        JOptionPane.showMessageDialog(
            this,
            "Last name must contain letters only."
        );

        return;
    }

    // SQL INSERT
    String sql =
        "INSERT INTO customers " +
        "(first_name, last_name, contact_number) " +
        "VALUES (?, ?, ?)";

    try (
        Connection conn = DatabaseConnection.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql)
    ) {

        pst.setString(1, firstName);
        pst.setString(2, lastName);
        pst.setString(3, contact);

        int added = pst.executeUpdate();

        if (added > 0) {

            JOptionPane.showMessageDialog(
                this,
                "Customer added successfully!"
            );

            // Refresh JTable
            refreshCustomerTable();

            // Clear fields
            txtCustomerId.setText("");
            txtFirstName.setText("");
            txtLastName.setText("");
            txtContact.setText("");
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error adding customer:\n" + e.getMessage()
        );
    }   // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

