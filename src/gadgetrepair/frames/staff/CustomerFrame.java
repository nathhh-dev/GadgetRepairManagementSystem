    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed

 String search = txtCustomerSearch.getText().trim();

    DefaultTableModel model =
        (DefaultTableModel) tblCustomers.getModel();

    if (search.isEmpty()) {
        refreshCustomerTable();
        return;
    }

    model.setRowCount(0);

    String sql =
        "SELECT customer_id, first_name, last_name, contact_number " +
        "FROM customers " +
        "WHERE is_active = 1 AND (" +
        "CAST(customer_id AS CHAR) LIKE ? OR " +
        "first_name LIKE ? OR " +
        "last_name LIKE ?) " +
        "ORDER BY customer_id";

    try (
        Connection conn = DatabaseConnection.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql)
    ) {

        String keyword = "%" + search + "%";

        pst.setString(1, keyword);
        pst.setString(2, keyword);
        pst.setString(3, keyword);

        ResultSet rs = pst.executeQuery();

        boolean found = false;

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("customer_id"),
                rs.getString("first_name"),
                rs.getString("last_name"),
                rs.getString("contact_number")
            });

            found = true;
        }

        if (!found) {

            JOptionPane.showMessageDialog(
                this,
                "Customer not found."
            );

            refreshCustomerTable();
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error searching customers:\n" + e.getMessage()
        );
    }
    }//GEN-LAST:event_btnSearchActionPerformed

